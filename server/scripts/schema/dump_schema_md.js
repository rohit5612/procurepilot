/**
 * Dump public schema from PostgreSQL to docs/database_schema.md
 * Run from repo root: node server/scripts/schema/dump_schema_md.js
 * Requires .env (or server/.env) with DB_HOST, DB_PORT, DB_NAME, DB_USER, DB_PASSWORD
 */
import { query, closeDatabase } from '../../src/database/connection.js';
import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));

async function getTables() {
  const res = await query(`
    SELECT table_name
    FROM information_schema.tables
    WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
    ORDER BY table_name
  `);
  return res.rows.map((r) => r.table_name);
}

async function getColumns(table) {
  const res = await query(
    `SELECT column_name, data_type, is_nullable, column_default
     FROM information_schema.columns
     WHERE table_schema = 'public' AND table_name = $1
     ORDER BY ordinal_position`,
    [table]
  );
  return res.rows;
}

async function getPrimaryKeys(table) {
  const res = await query(
    `SELECT kcu.column_name
     FROM information_schema.table_constraints tc
     JOIN information_schema.key_column_usage kcu
       ON tc.constraint_name = kcu.constraint_name
      AND tc.table_schema = kcu.table_schema
     WHERE tc.table_schema = 'public'
       AND tc.table_name = $1
       AND tc.constraint_type = 'PRIMARY KEY'
     ORDER BY kcu.ordinal_position`,
    [table]
  );
  return res.rows.map((r) => r.column_name);
}

async function getForeignKeys(table) {
  const res = await query(
    `SELECT c.conname AS constraint_name, pg_get_constraintdef(c.oid) AS definition
     FROM pg_constraint c
     JOIN pg_class t ON c.conrelid = t.oid
     JOIN pg_namespace n ON n.oid = t.relnamespace
     WHERE n.nspname = 'public'
       AND t.relname = $1
       AND c.contype = 'f'
     ORDER BY c.conname`,
    [table]
  );
  return res.rows;
}

async function getIndexes(table) {
  const res = await query(
    `SELECT indexname, indexdef
     FROM pg_indexes
     WHERE schemaname = 'public' AND tablename = $1
     ORDER BY indexname`,
    [table]
  );
  return res.rows;
}

function mdEscape(s) {
  if (s == null) return '';
  return String(s).replace(/\|/g, '\\|');
}

async function run() {
  const out = [];
  out.push('# Database Schema (public)');
  out.push('');
  out.push('Generated by querying PostgreSQL `information_schema` and `pg_*` catalogs.');
  out.push('');
  out.push('---');
  out.push('');

  const tables = await getTables();
  for (const table of tables) {
    out.push(`## Table: \`${table}\``);
    out.push('');

    const columns = await getColumns(table);
    out.push('| Column | Type | Nullable | Default |');
    out.push('|--------|------|----------|---------|');
    for (const col of columns) {
      const def = col.column_default ? mdEscape(col.column_default).slice(0, 60) : '';
      out.push(`| ${mdEscape(col.column_name)} | ${mdEscape(col.data_type)} | ${col.is_nullable === 'YES' ? 'YES' : 'NO'} | ${def} |`);
    }
    out.push('');

    const pks = await getPrimaryKeys(table);
    if (pks.length) {
      out.push('**Primary key:** `' + pks.join('`, `') + '`');
      out.push('');
    }

    const fks = await getForeignKeys(table);
    if (fks.length) {
      out.push('**Foreign keys:**');
      for (const fk of fks) {
        out.push('- `' + mdEscape(fk.constraint_name) + '`: `' + mdEscape(fk.definition) + '`');
      }
      out.push('');
    }

    const idx = await getIndexes(table);
    if (idx.length) {
      out.push('**Indexes:**');
      for (const i of idx) {
        out.push('- `' + mdEscape(i.indexname) + '`');
      }
      out.push('');
    }

    out.push('---');
    out.push('');
  }

  const md = out.join('\n');
  const docPath = join(__dirname, '..', '..', '..', 'docs', 'database_schema.md');
  writeFileSync(docPath, md, 'utf8');
  console.log('Written:', docPath);
}

run()
  .then(() => closeDatabase())
  .catch((err) => {
    console.error('Schema dump failed:', err);
    process.exit(1);
  });
