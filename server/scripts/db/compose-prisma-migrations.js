/**
 * Build Prisma migration folders from prisma/migration-manifest.json + legacy SQL.
 * Run: node scripts/db/compose-prisma-migrations.js
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const serverRoot = path.resolve(__dirname, '../..');
const prismaDir = path.join(serverRoot, 'prisma');
const manifestPath = path.join(prismaDir, 'migration-manifest.json');

function readSql(relativePath) {
  const full = path.resolve(prismaDir, relativePath);
  if (!fs.existsSync(full)) {
    throw new Error(`Missing SQL source: ${relativePath} (resolved ${full})`);
  }
  return fs.readFileSync(full, 'utf8');
}

/** Legacy SQL used explicit BEGIN/COMMIT; Prisma migrate deploy wraps the whole file in one transaction. */
function stripTransactionWrappers(sql) {
  return sql
    .split('\n')
    .filter((line) => !/^\s*BEGIN\s*;\s*$/i.test(line) && !/^\s*COMMIT\s*;\s*$/i.test(line))
    .join('\n');
}

function composeMigration(entry, index, total) {
  const parts = [];

  if (entry.nonTransactional) {
    parts.push('-- prisma-migrate: transactional = false');
  }

  parts.push(`-- ProcurePilot schema migration ${index + 1}/${total}: ${entry.title}`);
  parts.push(
    '-- Generated by scripts/db/compose-prisma-migrations.js — do not edit by hand; edit manifest + sources.\n'
  );

  if (entry.preamble) {
    parts.push(readSql(entry.preamble));
    parts.push('');
  }

  for (const src of entry.sources || []) {
    parts.push(`-- ----- source: ${src} -----`);
    parts.push(stripTransactionWrappers(readSql(src)));
    parts.push('');
  }

  return parts.join('\n');
}

function main() {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const migrationsRoot = path.join(prismaDir, 'migrations');
  const total = manifest.migrations.length;

  if (!fs.existsSync(migrationsRoot)) {
    fs.mkdirSync(migrationsRoot, { recursive: true });
  }

  manifest.migrations.forEach((entry, index) => {
    const dir = path.join(migrationsRoot, entry.folder);
    fs.mkdirSync(dir, { recursive: true });
    const sql = composeMigration(entry, index, total);
    fs.writeFileSync(path.join(dir, 'migration.sql'), sql, 'utf8');
    console.log(`Wrote ${entry.folder}/migration.sql`);
  });

  const lockPath = path.join(migrationsRoot, 'migration_lock.toml');
  if (!fs.existsSync(lockPath)) {
    fs.writeFileSync(lockPath, '# Please do not edit this file manually\nprovider = "postgresql"\n', 'utf8');
  }

  console.log(`\nComposed ${manifest.migrations.length} Prisma migrations.`);
}

main();
